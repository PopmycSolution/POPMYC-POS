/**
 * copy-frontend.js
 * ================
 * Copies the current React production build from:
 *   ../frontend/dist/
 * into:
 *   ../backend/staticfiles/
 *
 * This must run BEFORE Electron Builder packages the application so that
 * the bundled backend/staticfiles/ contains the current frontend build.
 *
 * How it fits into the architecture
 * -----------------------------------
 * - main.js loads BACKEND_URL (http://127.0.0.1:8000) after the Django backend starts.
 * - Django uses WhiteNoise + settings_desktop.py to serve static files from
 *   backend/staticfiles/.
 * - desktop_launcher.py runs `collectstatic --noinput` on first launch to merge
 *   Django admin/DRF statics into staticfiles/, then skips on subsequent runs
 *   if index.html already exists.
 * - Therefore backend/staticfiles/ must contain the current React SPA BEFORE
 *   it is packaged into app.asar, so the installer ships the right frontend.
 *
 * What this script does
 * ----------------------
 * 1. Verify frontend/dist exists and contains index.html.
 * 2. Clear only the React SPA files from backend/staticfiles/
 *    (index.html + assets/) — Django admin/DRF statics are left untouched
 *    because they are re-generated by collectstatic on first launch.
 * 3. Copy frontend/dist/ → backend/staticfiles/.
 * 4. Print a summary with file count and sizes.
 *
 * Usage
 * ------
 *   node scripts/copy-frontend.js
 *
 * Called automatically by the npm build scripts in package.json:
 *   npm run copy:frontend         — copy only
 *   npm run build:unpacked        — copy + electron-builder
 *   npm run build                 — copy + electron-builder (installer)
 */

'use strict';

const fs   = require('fs');
const path = require('path');

// ── Paths ─────────────────────────────────────────────────────────────────────

const DESKTOP_DIR     = path.join(__dirname, '..');
const FRONTEND_DIST   = path.join(DESKTOP_DIR, '..', 'frontend', 'dist');
const BACKEND_STATIC  = path.join(DESKTOP_DIR, '..', 'backend', 'staticfiles');

// ── Helpers ───────────────────────────────────────────────────────────────────

function fail(msg) {
  console.error('\n❌  COPY FRONTEND FAILED: ' + msg + '\n');
  process.exit(1);
}

function formatBytes(bytes) {
  if (bytes < 1024)       return bytes + ' B';
  if (bytes < 1048576)    return (bytes / 1024).toFixed(1) + ' KB';
  return (bytes / 1048576).toFixed(2) + ' MB';
}

/**
 * Recursively copy src directory into dst, creating dst if needed.
 * Returns { files: number, bytes: number }.
 */
function copyDir(src, dst) {
  let files = 0;
  let bytes = 0;

  fs.mkdirSync(dst, { recursive: true });

  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const srcPath = path.join(src, entry.name);
    const dstPath = path.join(dst, entry.name);

    if (entry.isDirectory()) {
      const sub = copyDir(srcPath, dstPath);
      files += sub.files;
      bytes += sub.bytes;
    } else if (entry.isFile()) {
      fs.copyFileSync(srcPath, dstPath);
      bytes += fs.statSync(dstPath).size;
      files++;
    }
  }

  return { files, bytes };
}

/**
 * Remove only the React SPA artefacts from backend/staticfiles/:
 *   - index.html        (React entry point)
 *   - assets/           (Vite-generated JS/CSS bundles — hashed filenames)
 *   - *.png, *.jpg, *.svg, *.ico  (top-level image assets from public/)
 *
 * Django admin/ and rest_framework/ and guardian/ directories are left intact
 * because collectstatic will regenerate them on first launch if missing.
 * We do NOT want to wipe those because it would force collectstatic to run
 * (slow) on every desktop start rather than only when upgrading.
 */
function clearSpaBuildArtefacts(dir) {
  if (!fs.existsSync(dir)) return;

  // Remove assets/ (all hashed JS/CSS bundles from Vite)
  const assetsDir = path.join(dir, 'assets');
  if (fs.existsSync(assetsDir)) {
    fs.rmSync(assetsDir, { recursive: true, force: true });
    console.log('  Cleared: staticfiles/assets/');
  }

  // Remove index.html (SPA entry point)
  const indexHtml = path.join(dir, 'index.html');
  if (fs.existsSync(indexHtml)) {
    fs.rmSync(indexHtml, { force: true });
    console.log('  Cleared: staticfiles/index.html');
  }

  // Remove any top-level image/manifest files copied from frontend/public/
  const topLevelAssetExts = new Set(['.png', '.jpg', '.jpeg', '.gif', '.ico', '.svg', '.webp', '.json']);
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isFile()) {
      const ext = path.extname(entry.name).toLowerCase();
      if (topLevelAssetExts.has(ext)) {
        fs.rmSync(path.join(dir, entry.name), { force: true });
        console.log(`  Cleared: staticfiles/${entry.name}`);
      }
    }
  }
}

// ── Main ──────────────────────────────────────────────────────────────────────

console.log('\n📦  copy-frontend.js — copying React build into backend/staticfiles/\n');

// 1. Verify source exists
if (!fs.existsSync(FRONTEND_DIST)) {
  fail(
    `frontend/dist not found at:\n    ${FRONTEND_DIST}\n\n` +
    '    Run:  cd frontend && npm run build\n' +
    '    then re-run:  cd desktop && npm run build:unpacked'
  );
}

const distIndex = path.join(FRONTEND_DIST, 'index.html');
if (!fs.existsSync(distIndex)) {
  fail(
    `frontend/dist/index.html not found — the frontend build may be incomplete.\n` +
    `    Expected: ${distIndex}\n` +
    '    Run:  cd frontend && npm run build'
  );
}

console.log(`  Source  : ${FRONTEND_DIST}`);
console.log(`  Target  : ${BACKEND_STATIC}`);

// 2. Clear stale SPA build artefacts from staticfiles/
console.log('\n  Clearing stale SPA artefacts from staticfiles/ …');
clearSpaBuildArtefacts(BACKEND_STATIC);

// 3. Copy frontend/dist/ → backend/staticfiles/
console.log('\n  Copying current frontend build …');
const { files, bytes } = copyDir(FRONTEND_DIST, BACKEND_STATIC);

// 4. Verify the copy
const copiedIndex = path.join(BACKEND_STATIC, 'index.html');
if (!fs.existsSync(copiedIndex)) {
  fail(`index.html was not copied to staticfiles/ — something went wrong.`);
}

console.log(`\n✅  Frontend copied successfully:`);
console.log(`    Files : ${files}`);
console.log(`    Size  : ${formatBytes(bytes)}`);
console.log(`    Target: ${BACKEND_STATIC}\n`);
